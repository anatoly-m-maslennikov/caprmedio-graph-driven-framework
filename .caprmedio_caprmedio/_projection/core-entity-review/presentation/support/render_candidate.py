def path_parts(display_path: str) -> list[str]:
    """Return operator-visible segments: ``A.B/C: D`` -> A, .B, /C, : D."""
    parts = re.split(r"([/.:@])", display_path)
    if not parts or not parts[0]:
        raise ValueError(f"invalid empty display path: {display_path!r}")
    result = [parts[0]]
    for index in range(1, len(parts), 2):
        if index + 1 >= len(parts) or not parts[index + 1]:
            raise ValueError(f"invalid terminal display operator: {display_path!r}")
        result.append(parts[index] + parts[index + 1])
    return result


def mark_label(identity: str, disposition: str, unresolved_drop: set[str]) -> str:
    if identity in unresolved_drop:
        return "QUESTION; DROP CANDIDATE unresolved"
    labels = {
        "retain": "RETAIN",
        "question": "QUESTION",
        "consolidate": "CONSOLIDATE CANDIDATE",
        "generalize": "GENERALIZE CANDIDATE",
    }
    try:
        return labels[disposition]
    except KeyError as error:
        raise ValueError(f"unsupported disposition for {identity}: {disposition}") from error


def make_tree(rows: list[dict[str, Any]]) -> dict[str, Any]:
    root: dict[str, Any] = {"children": {}, "identity": None, "mark": None}
    for row in sorted(rows, key=lambda item: (item["display_path"], item["identity"])):
        node = root
        for label in path_parts(row["display_path"]):
            node = node["children"].setdefault(label, {"children": {}, "identity": None, "mark": None})
        if node["identity"] is not None:
            raise ValueError(f"duplicate display leaf: {row['display_path']!r}")
        node["identity"] = row["identity"]
        node["mark"] = row["mark"]
    return root


def render_tree(tree: dict[str, Any], indent: int = 0) -> list[str]:
    lines: list[str] = []
    for label in sorted(tree["children"], key=str.casefold):
        node = tree["children"][label]
        suffix = (
            f" [original identity: {node['identity']}; {node['mark']}]"
            if node["identity"] is not None
            else " (prefix support only)"
        )
        lines.append(" " * indent + label + suffix)
        lines.extend(render_tree(node, indent + 2))
    return lines


def compact_ref(pointer: dict[str, Any]) -> str:
    key = pointer["source_ref_key"]
    return key.split(":", 1)[0]


def review_row_summary(row: dict[str, Any]) -> str:
    proposal = row["review_row"].get("proposal")
    if not proposal:
        return "No semantic replacement is proposed."
    if isinstance(proposal, str):
        return proposal
    target = next((proposal[key] for key in ("candidate_display_parent", "candidate_display_family", "candidate_display_name") if proposal.get(key)), None)
    basis = proposal.get("candidate_basis")
    risk = proposal.get("lost_distinctions_risk")
    parts = []
    if target:
        parts.append(f"display target: `{target}`")
    if basis:
        parts.append(str(basis))
    if risk:
        parts.append(f"risk retained: {risk}")
    return "; ".join(parts) if parts else "Structured proposal retained in nodes.dispositions.json."


def markdown_link(relative: str, label: str) -> str:
    return f"[{label}]({relative})"


