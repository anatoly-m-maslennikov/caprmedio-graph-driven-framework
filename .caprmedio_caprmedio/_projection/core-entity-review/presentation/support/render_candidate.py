def assert_safe_output_directory() -> None:
    """Reject symlinked/non-directory routing before any output is created."""
    directory = PRESENTATION_DIR
    while True:
        if directory.is_symlink() or not directory.is_dir():
            raise SystemExit(f"unsafe output directory: {directory}")
        if directory == REPO_ROOT:
            break
        if REPO_ROOT not in directory.parents:
            raise SystemExit(f"output directory escapes repository: {directory}")
        directory = directory.parent


def persist_outputs(expected: dict[str, bytes]) -> None:
    """Preflight every path, then exclusively create only genuinely absent files."""
    assert_safe_output_directory()
    missing: list[tuple[Path, bytes]] = []
    for name, content in expected.items():
        path = PRESENTATION_DIR / name
        if path.parent != PRESENTATION_DIR or path.is_symlink():
            raise SystemExit(f"unsafe output path: {path}")
        if path.exists():
            if not path.is_file():
                raise SystemExit(f"non-file output path: {path}")
            if path.read_bytes() != content:
                raise SystemExit(f"refusing to overwrite mismatching output: {path}")
        else:
            missing.append((path, content))

    created: list[tuple[Path, bytes]] = []
    try:
        for path, content in missing:
            # x mode provides exclusive creation if another writer races after preflight.
            with path.open("xb") as output:
                output.write(content)
                output.flush()
                os.fsync(output.fileno())
            created.append((path, content))
    except Exception:
        # Remove only files this invocation exclusively created and whose bytes still match.
        for path, content in reversed(created):
            if path.exists() and not path.is_symlink() and path.is_file() and path.read_bytes() == content:
                path.unlink()
        raise


def verify_outputs(expected: dict[str, bytes]) -> None:
    assert_safe_output_directory()
    failures = []
    for name, content in expected.items():
        path = PRESENTATION_DIR / name
        if path.is_symlink() or not path.is_file() or path.read_bytes() != content:
            failures.append(name)
    if failures:
        raise SystemExit("verification failed: " + ", ".join(failures))


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--persist", action="store_true", help="create absent byte-exact outputs")
    mode.add_argument("--verify-output", action="store_true", help="verify existing output bytes")
    args = parser.parse_args()
    expected = expected_outputs()
    if args.verify_output:
        verify_outputs(expected)
        print("verified", *(f"{name}:{sha256_bytes(content)}" for name, content in sorted(expected.items())))
        return 0
    if args.persist:
        persist_outputs(expected)
        print("persisted", *(f"{name}:{sha256_bytes(content)}" for name, content in sorted(expected.items())))
        return 0
    print("dry-run", *(f"{name}:{sha256_bytes(content)}" for name, content in sorted(expected.items())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
